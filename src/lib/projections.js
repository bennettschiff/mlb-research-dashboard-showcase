// ── Projection Lookup ──
export function normalizeName(name) {
  return (name || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z ]/g, "").replace(/\s+/g, " ").trim();
}

export function findProjection(name, team, list) {
  if (!name) return null;
  const norm = normalizeName(name);
  const nameMatches = list.filter(p => normalizeName(p.n) === norm);
  if (nameMatches.length > 0) {
    // 1. Exact name + team match — always preferred
    if (team) {
      const teamExact = nameMatches.find(p => p.t === team);
      if (teamExact) return teamExact;
      // Name matched but every projection entry has a different known team → wrong player, refuse
      // e.g. "Max Muncy (ATH)" should not receive "Max Muncy (LAD)" projection
      if (nameMatches.every(p => p.t && p.t !== team)) return null;
    }
    // 2. Unique name match with no conflicting team info
    if (nameMatches.length === 1) return nameMatches[0];
    // 3. Multiple entries, no team to disambiguate → refuse rather than guess
    return null;
  }
  // 4. Last-name + team fallback (handles nickname / middle-name variants)
  const lastName = norm.split(" ").pop();
  const teamMatches = list.filter(p => {
    const pLast = normalizeName(p.n).split(" ").pop();
    return pLast === lastName && (!team || p.t === team);
  });
  if (teamMatches.length === 1) return teamMatches[0];
  const lastOnly = list.filter(p => normalizeName(p.n).split(" ").pop() === lastName);
  if (lastOnly.length === 1) return lastOnly[0];
  return null;
}

export function getBatterProj(name, team) { return findProjection(name, team, PROJ_BATTERS); }
export function getPitcherProj(name, team) { return findProjection(name, team, PROJ_PITCHERS); }

export function batterProjRates(p) {
  if (!p) return null;
  const singles = p.h - p.d2 - p.d3 - p.hr;
  const tb = singles + p.d2 * 2 + p.d3 * 3 + p.hr * 4;
  const games = 150;
  return {
    avg: parseFloat(p.avg) || p.h / p.ab,
    ops: parseFloat(p.ops) || 0,
    h_per_game: p.h / games, hr_rate: p.hr / p.ab, hr_per_game: p.hr / games,
    d1_rate: singles / p.ab, d2_rate: p.d2 / p.ab, d3_rate: p.d3 / p.ab,
    tb_per_game: tb / games, sb_per_game: p.sb / games,
    singles, d2: p.d2, d3: p.d3, hr: p.hr, tb, sb: p.sb,
    h: p.h, ab: p.ab, bb: p.bb, r: p.r, rbi: p.rbi,
    slg: tb / p.ab,
  };
}

export function pitcherProjRates(p) {
  if (!p) return null;
  const bf = p.ip * 3 + p.h + p.bb;
  const k9 = p.k / (p.ip / 9);
  const bb9 = p.bb / (p.ip / 9);
  const baa = p.h / (bf - p.bb);
  const k_pct = p.k / bf;
  const starts = p.ty === "SP" ? Math.round(p.ip / 6) : null;
  const k_per_start = starts ? p.k / starts : null;
  return { era: p.era, whip: p.whip, k9, bb9, baa, k_pct, bf, k: p.k, ip: p.ip, h: p.h, er: p.er, bb: p.bb, starts, k_per_start, type: p.ty, w: p.w };
}
